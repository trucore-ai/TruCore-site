interface PageProps {
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}

/**
 * Generate dynamic metadata for the verify page.
 * Uses canonical URL helpers from share-utils for consistent proof URLs.
 */
export async function generateMetadata({ searchParams }: PageProps): Promise<Metadata> {
  const params = await searchParams;
  const hash = typeof params.hash === "string" ? params.hash : undefined;
  const from = params.from;
  const isFromShare = from === "share";

  // Canonical site origin for metadata URLs
  const siteOrigin = getCanonicalSiteOrigin();

  // Build OG image URL using canonical helper
  const ogImageUrl = hash
    ? buildOgPreviewUrl(hash)
    : `${siteOrigin}/api/og/receipt`;

  // Dynamic title for shared receipts
  const title = isFromShare
    ? "Protected Trade Receipt — TruCore"
    : "Verify ATF Receipt Hash";

  const description = isFromShare
    ? "This trade was evaluated, enforced, and recorded by TruCore Agent Transaction Firewall."
    : "Validate deterministic receipt hashes generated by Agent Transaction Firewall.";

  // Canonical URL for the page (without from=share for metadata URL)
  const pageUrl = hash
    ? `${siteOrigin}/verify?hash=${encodeURIComponent(hash)}`
    : `${siteOrigin}/verify`;

  return {
    title,
    description,
    openGraph: {
      title,
      description,
      type: "website",
      url: pageUrl,
      images: [
        {
          url: ogImageUrl,
          width: 1200,
          height: 630,
          alt: "TruCore Receipt Verification",
        },
      ],
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: [ogImageUrl],
    },
  };
}

function parseHash(raw: string | string[] | undefined): string {
  if (typeof raw !== "string") {
    return "";
  }

  return raw;
}

function parseFrom(raw: string | string[] | undefined): "verify" | "receipts" | "portal" | "share" {
  if (raw === "receipts" || raw === "portal" || raw === "share") {
    return raw;
  }

  return "verify";
}

function parseAutofetchSig(raw: string | string[] | undefined): boolean {
  return raw === "1";
}

